import { chromium, devices } from "@playwright/test";
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices["iPhone 13"] });
const page = await ctx.newPage();
page.on("console", m => console.log("[console]", m.type(), m.text().slice(0,400)));
page.on("pageerror", e => console.log("[pageerror]", String(e).slice(0,500)));
await page.goto("http://localhost:3001/shop", { waitUntil: "networkidle" });
await page.waitForTimeout(2000);
await page.locator("div[role=group][aria-label=Category]").getByRole("link", { name: "Chilies & Peppers", exact: true }).evaluate((el) => el.click());
await page.waitForTimeout(3000);
console.log("href:", await page.evaluate(() => window.location.href));
await browser.close();
